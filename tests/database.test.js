test("recovery replays committed pages after a crash before data flush", () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), "mydb-redo-"))
  const file = path.join(directory, "data.db")
  const host = createHost()
  let crash = false
  host.debug.crashPoint = (point) => {
    if (crash && point === "after-commit-before-page-flush") {
      throw new Error("simulated crash")
    }
  }
  const database = Database.open(file, host)
  database.execute("CREATE TABLE recovered_rows (id BIGINT PRIMARY KEY, value TEXT NOT NULL)")
  crash = true
  assert.throws(() => database.execute("INSERT INTO recovered_rows VALUES (1, 'durable')"), /simulated crash/)
  database.wal.close()
  database.pager.close()
  crash = false
  const reopened = Database.open(file, host)
  assert.deepEqual(reopened.execute("SELECT * FROM recovered_rows"), [[1n, "durable"]])
  reopened.close()
  fs.rmSync(directory, { recursive: true })
})

