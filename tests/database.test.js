test("primary unique not null and foreign keys reject invalid rows", () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), "mydb-constraints-"))
  const database = Database.open(path.join(directory, "data.db"), createHost())
  database.execute("CREATE TABLE users (id BIGINT PRIMARY KEY, email TEXT UNIQUE NOT NULL)")
  database.execute("CREATE TABLE orders (id BIGINT PRIMARY KEY, user_id BIGINT REFERENCES users(id))")
  database.execute("INSERT INTO users VALUES (1, 'ada@example.test')")
  assert.throws(() => database.execute("INSERT INTO users VALUES (2, 'ada@example.test')"), /Unique constraint/)
  assert.throws(() => database.execute("INSERT INTO users VALUES (3, NULL)"), /cannot be null/)
  assert.throws(() => database.execute("INSERT INTO orders VALUES (1, 99)"), /Foreign key/)
  database.execute("INSERT INTO orders VALUES (1, 1)")
  assert.throws(() => database.execute("DELETE FROM users WHERE id = 1"), /Delete restricted/)
  database.close()
  fs.rmSync(directory, { recursive: true })
})

test("joins limits aggregates and explain use the query pipeline", () => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), "mydb-query-"))
  const database = Database.open(path.join(directory, "data.db"), createHost())
  database.execute("CREATE TABLE users (id BIGINT PRIMARY KEY, name TEXT NOT NULL)")
  database.execute("CREATE TABLE orders (id BIGINT PRIMARY KEY, user_id BIGINT NOT NULL, amount INT NOT NULL)")
  database.execute("INSERT INTO users VALUES (1, 'Ada'), (2, 'Grace')")
  database.execute("INSERT INTO orders VALUES (1, 1, 20), (2, 1, 30), (3, 2, 40)")
  assert.deepEqual(database.execute("SELECT u.name, o.amount FROM users AS u INNER JOIN orders AS o ON o.user_id = u.id ORDER BY o.amount DESC LIMIT 2"), [["Grace", 40], ["Ada", 30]])
  assert.match(database.execute("EXPLAIN SELECT name FROM users WHERE id = 1"), /IndexScan/)
  assert.match(database.execute("EXPLAIN ANALYZE SELECT name FROM users WHERE id = 1"), /rows: 1, time: [0-9.]+ ms/)
  const prepared = database.prepare("SELECT name FROM users WHERE id = ?")
  assert.deepEqual(prepared.execute([1n]), [["Ada"]])
  const preparedUpdate = database.prepare("UPDATE users SET name = ? WHERE id = ?")
  assert.deepEqual(preparedUpdate.execute(["Augusta", 1n]), { status: "UPDATE", rows: 1 })
  assert.deepEqual(prepared.execute([1n]), [["Augusta"]])
  assert.throws(() => prepared.execute([]), /Expected 1 parameters/)
  database.close()
  fs.rmSync(directory, { recursive: true })
})

